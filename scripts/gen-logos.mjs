// Writes src/lib/logos.generated.ts from simple-icons (CC0). Skills with no icon fall back to a line icon.
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";
const MAP = {
  "LangChain": ["siLangchain"], "OpenAI API": ["siOpenai"], "Hugging Face": ["siHuggingface"],
  "Python": ["siPython"], "Java": ["siOpenjdk", "siJava"], "JavaScript": ["siJavascript"], "C / C++": ["siCplusplus"],
  "C#": ["siCsharp"], "FastAPI": ["siFastapi"], "Flask": ["siFlask"], "Django": ["siDjango"], ".NET": ["siDotnet"],
  "AWS": ["siAmazonaws", "siAmazonwebservices"], "Azure": ["siMicrosoftazure"], "Docker": ["siDocker"],
  "Kubernetes": ["siKubernetes"], "GitHub Actions": ["siGithubactions"], "Jenkins": ["siJenkins"],
  "PostgreSQL": ["siPostgresql"], "MongoDB": ["siMongodb"], "Redis": ["siRedis"], "SQLite": ["siSqlite"],
  "ROS 2": ["siRos"], "Shell": ["siGnubash"], "MLflow": ["siMlflow"],
};
const out = {}; const missing = [];
for (const [name, keys] of Object.entries(MAP)) {
  const k = keys.find((x) => si[x]);
  if (k) out[name] = { path: si[k].path, hex: "#" + si[k].hex }; else missing.push(name);
}
writeFileSync("src/lib/logos.generated.ts",
  "// generated by scripts/gen-logos.mjs, do not edit\nexport const LOGOS: Record<string, { path: string; hex: string }> = " + JSON.stringify(out) + ";\n");
console.log("logos:", Object.keys(out).length, "missing:", missing.join(", ") || "none");
